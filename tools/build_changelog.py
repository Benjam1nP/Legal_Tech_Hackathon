#!/usr/bin/env python3
"""Rebuild docs/CHANGELOG_DECISIONS.md from the git history.

The file is fully regenerated on every run, so it never causes merge
conflicts. A GitHub Action runs this after every push to main.

Decisions are taken from commit messages (see .gitmessage):

    Decision: Income limit is applied per household, not per parent
    Reason:   Art. 6 speaks of "Familie"; confirmed with the team
    Source:   Art. 6 Abs. 1 KiBG

Each "Decision:" line starts a new decision; the "Reason:" and "Source:"
lines after it belong to that decision.

Usage:
    python3 tools/build_changelog.py           # write the file
    python3 tools/build_changelog.py --check   # exit 1 if the file is outdated
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "docs" / "CHANGELOG_DECISIONS.md"
BOT_MARK = "[changelog-bot]"
MAX_FILES = 12
FIELD_RE = re.compile(r"^\s*(Decision|Reason|Source)\s*:\s*(.*)$", re.IGNORECASE)

REC, UNIT = "\x1e", "\x1f"


def git(*args: str) -> str:
    return subprocess.run(
        ["git", *args], cwd=ROOT, check=True, capture_output=True, text=True
    ).stdout


def load_commits() -> list[dict]:
    fmt = UNIT.join(["%H", "%h", "%an", "%ad", "%s", "%b"]) + REC
    raw = git("log", "--no-merges", "--date=format:%Y-%m-%d %H:%M", f"--format={fmt}")
    commits = []
    for record in raw.split(REC):
        record = record.strip("\n")
        if not record:
            continue
        full, short, author, date, subject, body = record.split(UNIT)
        if BOT_MARK in subject:
            continue
        files = [
            line
            for line in git("show", "--name-status", "--format=", full).splitlines()
            if line.strip()
        ]
        commits.append(
            {
                "short": short,
                "author": author,
                "date": date,
                "subject": subject,
                "decisions": parse_decisions(body),
                "files": files,
            }
        )
    return commits


def parse_decisions(body: str) -> list[dict]:
    decisions: list[dict] = []
    for line in body.splitlines():
        match = FIELD_RE.match(line)
        if not match:
            continue
        key, value = match.group(1).lower(), match.group(2).strip()
        if not value:
            continue
        if key == "decision":
            decisions.append({"decision": value})
        elif decisions:
            decisions[-1][key] = value
    return decisions


def describe_files(files: list[str]) -> str:
    labels = {"A": "added", "M": "changed", "D": "deleted", "R": "renamed"}
    items = []
    for line in files[:MAX_FILES]:
        parts = line.split("\t")
        status = labels.get(parts[0][:1], parts[0])
        path = parts[-1]
        items.append(f"`{path}` ({status})")
    more = len(files) - MAX_FILES
    if more > 0:
        items.append(f"and {more} more")
    return ", ".join(items)


def render(commits: list[dict]) -> str:
    out = [
        "# Changes and decisions",
        "",
        "<!-- Generated by tools/build_changelog.py after every push. Do not edit by",
        "     hand: write decisions into commit messages instead (see RULEBOOK.md). -->",
        "",
        "## Decisions",
        "",
    ]
    decisions = [(c, d) for c in commits for d in c["decisions"]]
    if decisions:
        out += [
            "| Date | Decision | Reason | Source | Commit | By |",
            "|---|---|---|---|---|---|",
        ]
        for c, d in decisions:
            cells = [
                c["date"][:10],
                d["decision"],
                d.get("reason", "–"),
                d.get("source", "–"),
                f"`{c['short']}`",
                c["author"],
            ]
            out.append(
                "| " + " | ".join(cell.replace("|", "\\|") for cell in cells) + " |"
            )
    else:
        out.append("_No decisions recorded yet._")

    out += ["", "## Change log", ""]
    current_day = None
    for c in commits:
        day = c["date"][:10]
        if day != current_day:
            if current_day is not None:
                out.append("")
            out += [f"### {day}", ""]
            current_day = day
        out.append(
            f"- **{c['subject']}** (`{c['short']}`, {c['author']}, {c['date'][11:]})"
        )
        if c["decisions"]:
            for d in c["decisions"]:
                out.append(f"  - Decision: {d['decision']}")
        if c["files"]:
            out.append(f"  - Files: {describe_files(c['files'])}")
    if current_day is not None:
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="only report if outdated")
    args = parser.parse_args()

    content = render(load_commits())
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != content:
            print(f"{OUTPUT.relative_to(ROOT)} is outdated")
            return 1
        print(f"{OUTPUT.relative_to(ROOT)} is up to date")
        return 0

    OUTPUT.parent.mkdir(exist_ok=True)
    OUTPUT.write_text(content, encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(ROOT)} ({len(content.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
